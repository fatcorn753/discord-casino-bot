"""/ヘルプ — 遊び方の一覧。"""

import discord
from discord import app_commands
from discord.ext import commands

from core import ui
from play.common import MAX_BET, MIN_BET


class Help(commands.Cog):
    def __init__(self, bot):
        self.bot = bot

    @app_commands.command(name="ヘルプ", description="📖 遊び方とコマンドの一覧")
    async def help(self, interaction: discord.Interaction):
        e = ui.embed("📖 ペリカカジノ", "ゲーム内の仮想通貨「ペリカ」で遊ぶ、お遊び用のカジノです。\n"
                     "**現実のお金とは関係なく、換金もできません。** 遊びすぎにはご注意を。\n\n"
                     "**はじめの3ステップ**\n① `/ペリカ デイリー` でペリカをもらう\n② `/カジノ コイン` で賭け金を決めて遊ぶ\n③ `/ペリカ ミッション` で今日の目標を見る", ui.GOLD)
        e.add_field(name="💴 まずはここから", value="\n".join([
            "`/ペリカ デイリー` — **6時間ごと**（日本時間の0・6・12・18時に切り替わる）に受け取れるボーナス。連続ログイン（日数）で増える",
            "`/ペリカ ミッション` — 毎日3つのミッション。達成で自動的にペリカがもらえる（連勝も記録）",
            "`/ペリカ 残高` — 残高と成績（勝率・損益・最大連勝）",
            "`/ペリカ ランキング` — ペリカの多い順",
            "📣 **毎週月曜0時**に、先週のゲームの稼ぎ1位が自動で発表され、限定称号「👑週間王者」が贈られます（コマンドは不要）",
            "`/ペリカ 送金` — 友達に送る（手数料10%・1日の上限あり）",
            "`/ペリカ 履歴` — 最近の増減（1ゲーム1行）",
        ]), inline=False)
        e.add_field(name="📈 CSトークン（`/暗号`）", value="\n".join([
            "`価格` `チャート` — いまの価格と値動き（1分ごとに動く・全サーバー共通）",
            "`買う` `売る` `保有` — 売買と、持っている分の損益（手数料なし・小数で買える。売るは「半分」「全部」も選べる）",
            "`チャート` には、保有者の名前・取得価格・何％前後しているかも出る",
            "`チャート掲示` — チャートを自動更新で掲示（管理者）",
            "※ 値動きはランダムで、先を読んでも得はしません。ゲーム内の通貨です",
        ]), inline=False)
        e.add_field(name="🛍️ ショップ（`/ショップ`）", value="\n".join([
            "`一覧` — 称号・カードの色/アイコン・消耗品・名前の色を、ペリカで交換",
            "`購入` `持ち物` `使う` `外す` — 買う・確認する・身につける・外す",
            "`称号表示` — 称号をニックネームの後ろに付ける（例: たつ【ざわ…ざわ…】）",
            "※ 景品はゲーム内・サーバー内のものだけです（現実の価値はありません）",
        ]), inline=False)
        e.add_field(name="🎰 ゲーム（`/カジノ`）", value="\n".join([
            "`チンチロ` — 🎲 地下チンチロ。親と勝負。目が出なければ3回まで",
            "`パチンコ` — 🎰 地下パチンコ。玉・リール・リーチの演出つき",
            "`スロット` — 🍒 3つ揃いは 🍒5倍 🍋8倍 🍇15倍 🔔30倍 💎100倍 7️⃣500倍（🍒が1つでも0.3倍戻る）",
            "`コイン` — 🪙 表裏を当てる（当たりで1.95倍）",
            "`ブラックジャック` — 🃏 ヒット・スタンド・ダブル（ダブルは最初の2枚のとき）",
            "`ルーレット` — 🎡 色・偶奇・範囲・数字に賭ける",
            "賭け金の50倍以上の勝ちは「ジャックポット級」の特別演出です。",
            "どのゲームも、結果の下の 🔁 ボタンで同じ額（または倍）でもう一度遊べます。",
        ]), inline=False)
        e.add_field(name="🔧 管理者向け", value="\n".join([
            "`/ペリカ ランキング掲示` `/暗号 チャート掲示` — 自動更新で掲示（サーバー管理の権限が必要）",
        ]), inline=False)
        e.add_field(name="ルール", value=f"賭け金は {ui.pelica(MIN_BET)} 〜 {ui.pelica(MAX_BET)}。"
                    "同時に遊べるゲームは1つだけです。途中で Bot が止まった場合、賭け金は返ります。", inline=False)
        await interaction.response.send_message(embed=e, ephemeral=True)


async def setup(bot):
    await bot.add_cog(Help(bot))
