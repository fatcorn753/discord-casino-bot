"""突発イベントの告知用ゲーム見出し・フレーバー文言（プレゼンテーション静的テキスト層）。"""

EVENT_GAMES: dict[str, tuple[str, str]] = {
    "チンチロ": ("🎲 チンチロ大会", "親も子も熱くなる時間。"),
    "パチンコ": ("🎰 パチンコ爆裂タイム", "玉がよく入る気がする…！"),
    "スロット": ("🍒 スロット確変タイム", "リールが今日はよく回る。"),
    "ブラックジャック": ("🃏 ブラックジャック・ナイト", "21を狙うなら今夜。"),
    "ルーレット": ("🎡 ルーレット・フィーバー", "ボールの行方は誰にも読めない。"),
}


def event_copy(game: str) -> tuple[str, str]:
    """ゲーム名に対応する (タイトル, 一言) を返す（未知・廃止ゲームでも落ちない）。"""
    return EVENT_GAMES.get(game, (game, ""))
