"""経済共通・帝愛・債券カタログの構造的契約。"""

from collections.abc import Mapping
from typing import Protocol


class BondKindProto(Protocol):
    @property
    def key(self) -> str: ...
    @property
    def name(self) -> str: ...
    @property
    def emoji(self) -> str: ...
    @property
    def hours(self) -> int: ...
    @property
    def rate(self) -> int: ...
    @property
    def default_pct(self) -> int: ...
    @property
    def max_total(self) -> int: ...
    @property
    def sellable(self) -> bool: ...


class BondsCatalogProto(Protocol):
    @property
    def min_amount(self) -> int: ...
    @property
    def sale_discount_per_hour(self) -> float: ...
    @property
    def kinds(self) -> tuple[BondKindProto, ...]: ...


class TeiaiStatusProto(Protocol):
    @property
    def label(self) -> str: ...
    @property
    def mark(self) -> str | None: ...
    @property
    def name(self) -> str | None: ...


